// Menu edits as pure functions ("mutators": menu → new menu), shared by the
// two menu editors:
//  - Admin.jsx (phone/desktop browser): edits a local draft, saved as a
//    whole with "Salva modifiche";
//  - TillMenu.jsx (the till): every "Salva" applies one mutator at once,
//    inside a Firestore transaction on the latest saved menu (MenuApp.jsx >
//    handlePatch) — the till stays open all day, and writing back its own
//    copy of the whole menu would undo edits made meanwhile from a phone.
//
// Mutators find dishes and categories by id and throw MenuEditError when
// they're gone (deleted from another device in the meantime). They must be
// deterministic (ids generated by the caller), because the same mutator is
// applied both to the saved menu and to the local copy on screen.

export class MenuEditError extends Error {}

// Firestore rejects `undefined` field values: a menu that has no
// translations yet (a brand-new one, the demo menu) must not get
// `translations: undefined` when a dish is deleted or moved — the key is
// left out instead. Used by both editors.
export function withTranslations(menu, translations) {
  return translations === undefined ? menu : { ...menu, translations };
}

// Removes, from every saved language, the translation of an entry (or, if
// itemId is omitted, of the whole category) just deleted from the Italian
// menu — otherwise it would stay as orphaned data in `menu.translations`,
// never read again by anything (applyTranslation only walks the
// categories/entries still present) but still saved on every "Salva".
export function pruneTranslations(translations, catId, itemId) {
  if (!translations) return translations;
  let changed = false;
  const next = {};
  for (const [langCode, langData] of Object.entries(translations)) {
    const cat = langData?.categories?.[catId];
    if (!cat) {
      next[langCode] = langData;
      continue;
    }
    if (itemId) {
      if (!cat.items || !(itemId in cat.items)) {
        next[langCode] = langData;
        continue;
      }
      const items = { ...cat.items };
      delete items[itemId];
      next[langCode] = { ...langData, categories: { ...langData.categories, [catId]: { ...cat, items } } };
    } else {
      const categories = { ...langData.categories };
      delete categories[catId];
      next[langCode] = { ...langData, categories };
    }
    changed = true;
  }
  return changed ? next : translations;
}

// Moves an entry's translation from one category to another in every saved
// language, when the entry itself is moved to a different category —
// without this, pruneTranslations-style logic would mistake it for orphaned
// data and lose it on the next edit.
export function moveTranslationItem(translations, fromCatId, toCatId, itemId) {
  if (!translations) return translations;
  let changed = false;
  const next = {};
  for (const [langCode, langData] of Object.entries(translations)) {
    const fromCat = langData?.categories?.[fromCatId];
    const itemData = fromCat?.items?.[itemId];
    if (!itemData) {
      next[langCode] = langData;
      continue;
    }
    const fromItems = { ...fromCat.items };
    delete fromItems[itemId];
    const categories = { ...langData.categories, [fromCatId]: { ...fromCat, items: fromItems } };
    const toCat = categories[toCatId] || {};
    categories[toCatId] = { ...toCat, items: { ...(toCat.items || {}), [itemId]: itemData } };
    next[langCode] = { ...langData, categories };
    changed = true;
  }
  return changed ? next : translations;
}

function findItem(menu, itemId) {
  for (const c of menu.categories) {
    const item = c.items.find((it) => it.id === itemId);
    if (item) return { category: c, item };
  }
  throw new MenuEditError("Questo piatto non esiste più (forse è stato eliminato da un altro dispositivo).");
}

function requireCategory(menu, catId) {
  const category = menu.categories.find((c) => c.id === catId);
  if (!category) throw new MenuEditError("Questa categoria non esiste più (forse è stata eliminata da un altro dispositivo).");
  return category;
}

const mapCategory = (menu, catId, fn) => ({
  ...menu,
  categories: menu.categories.map((c) => (c.id === catId ? fn(c) : c)),
});

export const menuEdits = {
  updateFields: (fields) => (menu) => ({ ...menu, ...fields }),

  setTranslation: (lang, translation) => (menu) => ({
    ...menu,
    translations: { ...(menu.translations || {}), [lang]: translation },
  }),

  // Adding is idempotent (same id = already there): retrying after a timeout
  // whose transaction committed anyway must not create a copy.
  addCategory: (category) => (menu) => (
    menu.categories.some((c) => c.id === category.id) ? menu : { ...menu, categories: [...menu.categories, category] }
  ),

  updateCategory: (catId, fields) => (menu) => {
    requireCategory(menu, catId);
    return mapCategory(menu, catId, (c) => ({ ...c, ...fields }));
  },

  // "In comanda" for every dish of a category at once (e.g. all drinks off).
  setCategoryKitchenTicket: (catId, value) => (menu) => {
    requireCategory(menu, catId);
    return mapCategory(menu, catId, (c) => ({ ...c, items: c.items.map((it) => ({ ...it, kitchenTicket: value })) }));
  },

  removeCategory: (catId) => (menu) => {
    requireCategory(menu, catId);
    return withTranslations(
      { ...menu, categories: menu.categories.filter((c) => c.id !== catId) },
      pruneTranslations(menu.translations, catId),
    );
  },

  // direction: -1 (earlier) or +1 (later); no effect at the edge.
  moveCategory: (catId, direction) => (menu) => {
    const idx = menu.categories.findIndex((c) => c.id === catId);
    if (idx < 0) requireCategory(menu, catId);
    const to = idx + direction;
    if (to < 0 || to >= menu.categories.length) return menu;
    const categories = [...menu.categories];
    [categories[idx], categories[to]] = [categories[to], categories[idx]];
    return { ...menu, categories };
  },

  addItem: (catId, item) => (menu) => {
    if (menu.categories.some((c) => c.items.some((it) => it.id === item.id))) return menu;
    requireCategory(menu, catId);
    return mapCategory(menu, catId, (c) => ({ ...c, items: [...c.items, item] }));
  },

  updateItem: (itemId, fields) => (menu) => {
    const { category } = findItem(menu, itemId);
    return mapCategory(menu, category.id, (c) => ({
      ...c,
      items: c.items.map((it) => (it.id === itemId ? { ...it, ...fields } : it)),
    }));
  },

  removeItem: (itemId) => (menu) => {
    const { category } = findItem(menu, itemId);
    return withTranslations(
      mapCategory(menu, category.id, (c) => ({ ...c, items: c.items.filter((it) => it.id !== itemId) })),
      pruneTranslations(menu.translations, category.id, itemId),
    );
  },

  moveItem: (itemId, direction) => (menu) => {
    const { category } = findItem(menu, itemId);
    const idx = category.items.findIndex((it) => it.id === itemId);
    const to = idx + direction;
    if (to < 0 || to >= category.items.length) return menu;
    const items = [...category.items];
    [items[idx], items[to]] = [items[to], items[idx]];
    return mapCategory(menu, category.id, (c) => ({ ...c, items }));
  },

  // To the end of another category, carrying its translations along.
  moveItemToCategory: (itemId, toCatId) => (menu) => {
    const { category, item } = findItem(menu, itemId);
    requireCategory(menu, toCatId);
    if (category.id === toCatId) return menu;
    return withTranslations(
      {
        ...menu,
        categories: menu.categories.map((c) => {
          if (c.id === category.id) return { ...c, items: c.items.filter((it) => it.id !== itemId) };
          if (c.id === toCatId) return { ...c, items: [...c.items, item] };
          return c;
        }),
      },
      moveTranslationItem(menu.translations, category.id, toCatId, itemId),
    );
  },
};

// Several edits as one (e.g. a dish's fields + its new category, saved
// together with one "Salva").
export function combineEdits(...edits) {
  return (menu) => edits.filter(Boolean).reduce((m, edit) => edit(m), menu);
}
